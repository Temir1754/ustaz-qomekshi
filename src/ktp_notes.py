def get_explanatory_note(subject_label: str, lang: str) -> list[str] | None:
    """Возвращает список абзацев «Түсінік хат» для предмета, только на казахском —
    источник существует только на kk (см. модульный докстринг), поэтому для lang="ru"
    и для предметов без сохранённого текста ниже — возвращает None (раздел просто
    не добавляется, а не переводится/выдумывается)."""
    if lang != "kk":
        return None
    return KTP_EXPLANATORY_NOTES.get(subject_label.strip().lower())
